"""The results table: baseline against the finished system.

    interview report

Reads every `.metrics.json` under `evals/results/iteration-*/` and renders the comparison
in the shape agentic-workflows.md section 6 asks for, plus the per-iteration rows the
changelog cites. Writes `evals/results/report.md` and `evals/results/report.json`, so
every number a README quotes has a file under `evals/results/` behind it - ground rule 9.

**It refuses to build a table spanning two experiments.** Coverage measured against one CV
is not comparable with coverage measured against another, and a table is exactly where that
mistake stops being visible. Runs carry their lock id, so this can tell them apart.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any, Mapping, Sequence

import yaml

ROOT = Path(__file__).resolve().parents[2]

NO_LOCK = "(no lock)"


def collect(results_dir: Path) -> list[dict[str, Any]]:
    """Every measured run, in file order.

    **Every run, not the newest one per rung.** Keeping only the latest was the obvious
    thing while a rung was expected to be run once, and it silently discarded the only
    evidence for the property that turns out to matter most: whether the same interviewer,
    given the same opening answer, covers the same competencies twice running. A single
    run cannot show that, and a mean hides it. See `summarise`.
    """
    runs: list[dict[str, Any]] = []
    for path in sorted(results_dir.glob("iteration-*/session-*.metrics.json")):
        document = json.loads(path.read_text(encoding="utf-8"))
        if document.get("run_kind") != "measurement":
            continue
        if document.get("interrupted"):
            continue
        document["path"] = _relative(path)
        runs.append(document)
    return runs


def _relative(path: Path) -> str:
    """Repository-relative where possible, absolute otherwise.

    The same fallback `solution/application/experiment.py` uses. Without it a results
    directory outside the repository raises rather than rendering, which makes this
    untestable and would turn a moved directory into a crash instead of a longer link.
    """
    try:
        return str(path.resolve().relative_to(ROOT.resolve())).replace("\\", "/")
    except ValueError:
        return str(path).replace("\\", "/")


def by_iteration(runs: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
    """One summarised row per rung, in rung order."""
    grouped: dict[int, list[Mapping[str, Any]]] = defaultdict(list)
    for run in runs:
        grouped[int(run.get("metadata", {}).get("iteration", -1))].append(run)
    return [summarise(iteration, grouped[iteration]) for iteration in sorted(grouped)]


def summarise(iteration: int, runs: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """One rung's runs reduced to the row the tables need.

    The reported figure for a rung is its **worst** run, not its mean. A screen that
    covers everything four times in five still returns partial evidence about one
    candidate in five, and it is that candidate who is rejected on it. The mean is carried
    alongside so the spread is visible, but the floor is the number that describes what
    the system guarantees.
    """
    coverage = [float(r["coverage"]["value"]) for r in runs]
    latest = runs[-1]
    return {
        "iteration": iteration,
        "runs": len(runs),
        "coverage_floor": min(coverage) if coverage else 0.0,
        "coverage_mean": round(sum(coverage) / len(coverage), 3) if coverage else 0.0,
        "coverage_ceiling": max(coverage) if coverage else 0.0,
        "longest_chain": max(
            (int((r.get("allocation") or {}).get("longest_chain") or 0) for r in runs),
            default=0,
        ),
        "latest": latest,
        "all_runs": list(runs),
    }


def group_by_experiment(rows: Sequence[Mapping[str, Any]]) -> dict[str, list[Mapping[str, Any]]]:
    grouped: dict[str, list[Mapping[str, Any]]] = defaultdict(list)
    for row in rows:
        grouped[row.get("experiment_lock_id") or NO_LOCK].append(row)
    return dict(grouped)


def _percent(value: float | None) -> str:
    return "-" if value is None else f"{value:.0%}"


def _change(before: float | None, after: float | None) -> str:
    if before is None or after is None:
        return "-"
    delta = after - before
    return f"{delta:+.0%}"


def render_markdown(
    rows: Sequence[Mapping[str, Any]],
    baseline_iteration: int,
    solution_iteration: int,
    lock: Mapping[str, Any] | None,
) -> str:
    indexed = {int(r["iteration"]): r for r in rows}
    baseline = indexed.get(baseline_iteration)
    solution = indexed.get(solution_iteration)

    lines = [
        "# Results",
        "",
        "Generated by `interview report`. Every figure below is read from a "
        "`.metrics.json` beside the session record that produced it; nothing here is "
        "hand-entered.",
        "",
    ]

    if lock:
        lines += [
            f"**Experiment `{lock.get('lock_id')}`**, frozen {lock.get('frozen_at')} — "
            f"role `{lock.get('role')}`, case `{lock.get('case')}`. Every run below ran "
            "against identical inputs; `evals/experiment-lock.yaml` records their digests.",
            "",
        ]

    lines += [
        "## Baseline against the finished system",
        "",
        "**Coverage is reported as the worst run, not the mean.** A screen that covers "
        "everything four times in five still returns partial evidence about one candidate "
        "in five, and it is that candidate who is rejected on it. The mean and the spread "
        "are in the per-rung table below.",
        "",
        "| Metric | Simple baseline | Agent solution | Change |",
        "| --- | --- | --- | --- |",
    ]

    def figure(row: Mapping[str, Any] | None, key: str) -> float | None:
        if row is None:
            return None
        if key in ("coverage_floor", "coverage_mean"):
            return row.get(key)
        return row["latest"].get(key)

    for label, key in (
        ("Coverage, worst run (primary)", "coverage_floor"),
        ("Coverage, mean", "coverage_mean"),
        ("Carry-over rate (guardrail)", "carry_over_rate"),
        ("Grounding rate (guardrail)", "grounding_rate"),
    ):
        before, after = figure(baseline, key), figure(solution, key)
        lines.append(
            f"| {label} | {_percent(before)} | {_percent(after)} | {_change(before, after)} |"
        )

    chain_before = baseline.get("longest_chain") if baseline else None
    chain_after = solution.get("longest_chain") if solution else None
    chain_delta = (
        "-" if chain_before is None or chain_after is None else f"{chain_after - chain_before:+}"
    )
    lines.append(
        f"| Longest chain on one competency | {chain_before if chain_before is not None else '-'} "
        f"| {chain_after if chain_after is not None else '-'} | {chain_delta} |"
    )

    questions_before = baseline["latest"].get("questions_measured") if baseline else None
    questions_after = solution["latest"].get("questions_measured") if solution else None
    if questions_before is None or questions_after is None:
        delta = "-"
    else:
        delta = f"{questions_after - questions_before:+}"
    lines.append(
        f"| Questions asked | {questions_before or '-'} | {questions_after or '-'} | {delta} |"
    )

    if baseline is None or solution is None:
        missing = []
        if baseline is None:
            missing.append(f"iteration {baseline_iteration} (baseline)")
        if solution is None:
            missing.append(f"iteration {solution_iteration} (solution)")
        lines += [
            "",
            f"> Not yet measured: {', '.join(missing)}. The table fills in as the ladder is run.",
        ]

    lines += [
        "",
        "## Every rung",
        "",
        "One row per measured iteration, so the changelog can point at a number rather "
        "than describe one. **`judge` is the share of questions a model classified**, and "
        "since the keyword layer was removed it is the whole of it — the coverage "
        "figure rests on the judge, whose only external check is the hand-labelled "
        "agreement sample.",
        "",
        "**`n` is how many times the rung was run, and `worst – best` is the spread across "
        "those runs.** A rung run once has no spread and cannot say whether its coverage "
        "was reliable or lucky. **`chain`** is the longest run of consecutive questions on "
        "a single competency — what coverage cannot see, because coverage is a set.",
        "",
        "**Read the answer-time columns beside coverage.** Answers are not capped, so a "
        "respondent who talked longer would take fewer questions and cover less — and that "
        "would look exactly like an interviewer that got worse. These two columns are what "
        "tell the explanations apart.",
        "",
        "| Iteration | n | Coverage (worst) | worst – best | chain | Carry-over | Grounding "
        "| Questions | mean answer | answering | judge | Record |",
        "| ---: | ---: | ---: | :---: | ---: | ---: | ---: | ---: | ---: | ---: | :---: | --- |",
    ]

    for row in rows:
        latest = row["latest"]
        total = max(int(latest.get("questions_measured", 0)), 1)
        layers = latest.get("resolved_by", {})
        judge_share = layers.get("judge", 0) / total
        seconds = latest.get("answer_seconds") or {}
        spread = f"{row['coverage_floor']:.0%} – {row['coverage_ceiling']:.0%}"
        lines.append(
            f"| {row['iteration']} "
            f"| {row['runs']} "
            f"| {row['coverage_floor']:.0%} "
            f"| {spread} "
            f"| {row['longest_chain']} "
            f"| {latest['carry_over_rate']:.0%} "
            f"| {latest['grounding_rate']:.0%} "
            f"| {latest['questions_measured']} "
            f"| {seconds.get('mean', 0):.0f}s "
            f"| {seconds.get('total', 0) / 60:.1f} min "
            f"| {judge_share:.0%} "
            f"| [`{Path(latest['path']).name}`]({latest['path']}) |"
        )

    if not rows:
        lines.append(
            "| — | — | — | — | — | — | — | — "
            "| — | — | — | no measured run yet |"
        )

    lines += [
        "",
        "## Missed competencies, per rung",
        "",
        "Taken from the **worst** run of each rung: the competencies at least one run "
        "left unasked. A rung that covered everything on average still failed the "
        "candidate whose run is listed here.",
        "",
    ]
    if rows:
        for row in rows:
            worst = min(row["all_runs"], key=lambda r: r["coverage"]["value"])
            missed = ", ".join(worst["coverage"]["missed_slots"]) or "none"
            lines.append(f"- **iteration {row['iteration']}** — missed: {missed}")
    else:
        lines.append("No measured run yet.")

    lines.append("")
    return "\n".join(lines)


def render_conflict(grouped: Mapping[str, Sequence[Mapping[str, Any]]]) -> str:
    lines = [
        "",
        "  BLOCKED  the measured runs belong to more than one experiment",
        "",
        "           A coverage figure measured against one CV and slot plan is not",
        "           comparable with one measured against another, and a table is exactly",
        "           where that would stop being visible.",
        "",
    ]
    for lock_id, rows in sorted(grouped.items()):
        iterations = ", ".join(str(r["metadata"]["iteration"]) for r in rows)
        lines.append(f"           {lock_id}   iterations {iterations}")
    lines += [
        "",
        "     fix:  report on one experiment at a time. PREREGISTRATION.md section 4",
        "           requires the runs from the abandoned one to stay reported, so move",
        "           them aside rather than deleting them, and say so in CHANGELOG.md.",
        "",
    ]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    config = yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))
    iterations = config.get("iterations", {})
    results_dir = ROOT / "evals" / "results"

    runs = collect(results_dir)
    grouped = group_by_experiment(runs)
    if len(grouped) > 1:
        print(render_conflict(grouped))
        return 2

    rows = by_iteration(runs)

    lock_path = ROOT / config.get("experiment_lock", "evals/experiment-lock.yaml")
    lock = yaml.safe_load(lock_path.read_text(encoding="utf-8")) if lock_path.exists() else None

    markdown = render_markdown(
        rows,
        baseline_iteration=int(iterations.get("baseline", 0)),
        solution_iteration=int(iterations.get("solution", 10)),
        lock=lock,
    )

    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / "report.md").write_text(markdown, encoding="utf-8")
    (results_dir / "report.json").write_text(
        json.dumps(
            {
                "experiment": (lock or {}).get("lock_id"),
                "baseline_iteration": int(iterations.get("baseline", 0)),
                "solution_iteration": int(iterations.get("solution", 10)),
                "iterations": rows,
            },
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )

    print(markdown)
    where = str(results_dir.relative_to(ROOT)).replace("\\", "/")
    print(f"  written to {where}/report.md and {where}/report.json\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
